def glyph_to_bytes(rows):
    """Convierte 7 filas x 5 columnas en 5 bytes (columna-mayor, bit0=arriba)."""
    assert len(rows) == 7, rows
    cols = []
    for c in range(5):
        byte = 0
        for r in range(7):
            if rows[r][c] == '#':
                byte |= (1 << r)
        cols.append(byte)
    return cols


def main():
    # 95 glifos, ASCII 0x20 .. 0x7E.
    table = [glyph_to_bytes(GLYPHS.get(chr(c), ["....."] * 7))
             for c in range(0x20, 0x7F)]

    lines = []
    lines.append("/*")
    lines.append(" * font5x7.hpp - GENERADO automaticamente por tools/gen_font.py.")
    lines.append(" * NO EDITAR A MANO. Fuente 5x7 (5 bytes/glifo, bit0 = fila superior).")
    lines.append(" * Indice = (caracter - 0x20), cubre ASCII 0x20..0x7E.")
    lines.append(" */")
    lines.append("#ifndef PICO_REFLEX_FONT5X7_HPP")
    lines.append("#define PICO_REFLEX_FONT5X7_HPP")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("// Fuente 5x7: 95 glifos x 5 bytes.")
    lines.append("static const uint8_t FONT5X7[95][5] = {")
    for i, glyph in enumerate(table):
        ch = chr(i + 0x20)
        comment = ""
        if ch in GLYPHS:
            comment = " // 0x%02X '%s'" % (i + 0x20, ch)
        hexs = ", ".join("0x%02X" % b for b in glyph)
        lines.append("    {%s},%s" % (hexs, comment))
    lines.append("};")
    lines.append("")
    lines.append("#endif // PICO_REFLEX_FONT5X7_HPP")
    lines.append("")

    with open("include/font5x7.hpp", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("OK: include/font5x7.hpp generado con %d glifos definidos." % len(GLYPHS))


if __name__ == "__main__":
    main()
